// Builds the versioned bundles and their copies:
// - dist/core.js: the core (src/index.ts), ESM, no `node:*`, for every form including the Claude Code mod;
// - dist/node-host.js: the Node host, for the CLI and the OpenCode plugin;
// - dist/types/*.d.ts with dist/core.d.ts and dist/node-host.d.ts: the declarations for the two bundles;
// - the copies the packages ship: opencode/core/ and claude/core/ (core, node host, types);
// - the skills of every agent, skills/<agent>/<skill>/, from one source each in skills/source/<skill>/ (the same
//   text, the host's way of calling the tool), and the Claude Code ones again inside the mod (claude/skills/).
// `bun scripts/build.ts --check` only reports which generated files differ from a fresh build.

import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import ts from "typescript"

const root = join(import.meta.dir, "..").replace(/\\/g, "/")

export interface Bundle {
  /** Where the file goes, relative to the repository. */
  out: string
  text: string
}

const HEADER = "// Generated by scripts/build.ts from src/. Do not edit.\n"

async function bundle(entry: string, target: "browser" | "node"): Promise<string> {
  const result = await Bun.build({ entrypoints: [join(root, entry)], target, format: "esm", minify: false })
  if (!result.success) throw new AggregateError(result.logs, `build of ${entry} failed`)
  return HEADER + (await result.outputs[0]!.text()).replace(/\r\n/g, "\n")
}

/** Declarations of src/, one file per module, with `./x.ts` specifiers rewritten to `./x.js`. */
function declarations(): Bundle[] {
  const options: ts.CompilerOptions = {
    target: ts.ScriptTarget.ESNext,
    module: ts.ModuleKind.ESNext,
    moduleResolution: ts.ModuleResolutionKind.Bundler,
    lib: ["lib.esnext.d.ts"],
    types: ["node"],
    strict: true,
    skipLibCheck: true,
    declaration: true,
    emitDeclarationOnly: true,
    allowImportingTsExtensions: true,
    rootDir: `${root}/src`,
    outDir: `${root}/dist/types`,
    newLine: ts.NewLineKind.LineFeed,
  }
  const out: Bundle[] = []
  const program = ts.createProgram([`${root}/src/index.ts`, `${root}/src/node-host.ts`], options)
  const result = program.emit(undefined, (file, text) => {
    const rel = file.replace(/\\/g, "/").slice(root.length + 1)
    out.push({ out: rel, text: HEADER + text.replace(/(from\s+["']\.\/[^"']+)\.ts(["'])/g, "$1.js$2") })
  })
  if (result.emitSkipped) throw new Error("declaration emit failed")
  return out.sort((a, b) => a.out.localeCompare(b.out))
}

/** Every generated file with its expected content. */
export async function buildAll(): Promise<Bundle[]> {
  const core = await bundle("src/index.ts", "browser")
  const nodeHost = await bundle("src/node-host.ts", "node")
  const types = declarations()
  const dist: Bundle[] = [
    { out: "dist/core.js", text: core },
    { out: "dist/core.d.ts", text: `${HEADER}export * from "./types/index.js"\n` },
    { out: "dist/node-host.js", text: nodeHost },
    { out: "dist/node-host.d.ts", text: `${HEADER}export * from "./types/node-host.js"\n` },
    ...types,
  ]
  const copies = (prefix: string) => dist.map((b) => ({ out: b.out.replace(/^dist\//, `${prefix}/`), text: b.text }))
  return [...dist, ...copies("opencode/core"), ...copies("claude/core"), ...skills()]
}

