// Builds the versioned bundles: `dist/core.js` (the core, no `node:*`, for every form including the Claude Code
// mod) and `dist/node-host.js` (the Node host). `bun scripts/build.ts --check` only reports whether the files on
// disk match a fresh build.

import { readFileSync, writeFileSync, mkdirSync } from "node:fs"
import { dirname, join } from "node:path"

const root = join(import.meta.dir, "..")

export interface Bundle {
  /** Where the bundle goes, relative to the repository. */
  out: string
  text: string
}

const HEADER = "// Generated by scripts/build.ts from src/. Do not edit.\n"

async function bundle(entry: string, target: "browser" | "node", external: string[] = []): Promise<string> {
  const result = await Bun.build({
    entrypoints: [join(root, entry)],
    target,
    format: "esm",
    minify: false,
    external,
  })
  if (!result.success) throw new AggregateError(result.logs, `build of ${entry} failed`)
  const text = await result.outputs[0]!.text()
  return HEADER + text.replace(/\r\n/g, "\n")
}

/** Every generated file with its expected content. */
export async function buildAll(): Promise<Bundle[]> {
  const core = await bundle("src/index.ts", "browser")
  const nodeHost = await bundle("src/node-host.ts", "node")
  return [
    { out: "dist/core.js", text: core },
    { out: "dist/node-host.js", text: nodeHost },
  ]
}

/** The generated files that differ from disk. */
export async function stale(): Promise<string[]> {
  const out: string[] = []
  for (const b of await buildAll()) {
    let current = ""
    try {
      current = readFileSync(join(root, b.out), "utf8")
    } catch {}
    if (current !== b.text) out.push(b.out)
  }
  return out
}

if (import.meta.main) {
  if (process.argv.includes("--check")) {
    const diff = await stale()
    if (diff.length) {
      console.error(`stale: ${diff.join(", ")} (run bun scripts/build.ts)`)
      process.exit(1)
    }
    console.log("up to date")
  } else {
    for (const b of await buildAll()) {
      mkdirSync(dirname(join(root, b.out)), { recursive: true })
      writeFileSync(join(root, b.out), b.text)
      console.log(`wrote ${b.out} (${b.text.length} bytes)`)
    }
  }
}
