function fillSkill(text: string, host: string, skill: string): string {
  const h = HOSTS[host]!
  const out = text
    .replace("{{FRONTMATTER}}", h.frontmatter[skill] ?? "")
    .replace("{{CALLING}}", h.calling)
    .replace("{{SPAWN}}", h.spawn)
    .replace("{{AFTER}}", h.after)
    .replace("{{KEEPALIVE}}", h.keepalive)
    .replace("{{TRANSIENT}}", h.transient)
    .replace("{{WAIT}}", h.wait)
  const left = /\{\{\w+\}\}/.exec(out)
  if (left) throw new Error(`skills/source/${skill}/SKILL.md: ${left[0]} has no value for ${host}`)
  return out
}

/** skills/<agent>/<skill>/ for every agent, and the Claude Code ones inside the mod. */
function skills(): Bundle[] {
  const out: Bundle[] = []
  const source = join(root, "skills/source")
  for (const skill of readdirSync(source).sort())
    for (const host of Object.keys(HOSTS))
      for (const name of readdirSync(join(source, skill)).sort()) {
        const raw = readFileSync(join(source, skill, name), "utf8").replace(/\r\n/g, "\n")
        const text = name === "SKILL.md" ? fillSkill(raw, host, skill) : raw
        out.push({ out: `skills/${host}/${skill}/${name}`, text })
        if (host === "claude-code") out.push({ out: `claude/skills/${skill}/${name}`, text })
      }
  return out
}

/** claude/agents/<name>.md from opencode/agents/<name>.md: the body as it is, the frontmatter Claude Code's. */
function agents(): Bundle[] {
  const source = join(root, "opencode/agents")
  return readdirSync(source)
    .filter((name) => name.endsWith(".md"))
    .sort()
    .map((name) => {
      const raw = readFileSync(join(source, name), "utf8").replace(/\r\n/g, "\n")
      const [, front, body] = /^---\n([\s\S]*?)\n---\n([\s\S]*)$/.exec(raw) ?? []
      const description = /^description: (.*)$/m.exec(front ?? "")?.[1]
      if (body === undefined || !description) throw new Error(`opencode/agents/${name}: no frontmatter with a description`)
      return { out: `claude/agents/${name}`, text: `---\nname: ${name.replace(/\.md$/, "")}\ndescription: ${description}\n---\n${body}` }
    })
}

/** The generated files that differ from disk. */
export async function stale(): Promise<string[]> {
  const out: string[] = []
  for (const b of await buildAll()) {
    let current = ""
    try {
      current = readFileSync(join(root, b.out), "utf8")
    } catch {}
    if (current !== b.text) out.push(b.out)
  }
  return out
}

if (import.meta.main) {
  if (process.argv.includes("--check")) {
    const diff = await stale()
    if (diff.length) {
      console.error(`stale: ${diff.join(", ")} (run bun scripts/build.ts)`)
      process.exit(1)
    }
    console.log("up to date")
  } else {
    const all = await buildAll()
    for (const b of all) {
      mkdirSync(dirname(join(root, b.out)), { recursive: true })
      writeFileSync(join(root, b.out), b.text)
    }
    console.log(`wrote ${all.length} files (dist/, opencode/core/, claude/core/, skills/<agent>/, claude/skills/, claude/agents/)`)
  }
}
